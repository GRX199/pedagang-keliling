// Generate from a local database rebuilt from repository migrations, never production.
import { execFileSync } from 'node:child_process'
import { mkdir, writeFile } from 'node:fs/promises'

const psql = process.env.PSQL_PATH || 'psql'
const sql = `select jsonb_build_object(
  'tables', (select jsonb_agg(jsonb_build_object('name', c.relname, 'columns',
    (select jsonb_agg(jsonb_build_object('name', a.attname, 'type', format_type(a.atttypid,a.atttypmod),
      'nullable', not a.attnotnull, 'defaulted', d.adbin is not null, 'generated', a.attgenerated <> '') order by a.attnum)
      from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
      where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped),
    'relations', (select coalesce(jsonb_agg(jsonb_build_object('foreignKeyName', fk.conname,
      'columns', (select jsonb_agg(a.attname order by k.n) from unnest(fk.conkey) with ordinality k(id,n) join pg_attribute a on a.attrelid=c.oid and a.attnum=k.id),
      'isOneToOne', exists(select 1 from pg_constraint uq where uq.conrelid=c.oid and uq.contype in ('p','u') and uq.conkey=fk.conkey),
      'referencedRelation', rc.relname,
      'referencedColumns', (select jsonb_agg(a.attname order by k.n) from unnest(fk.confkey) with ordinality k(id,n) join pg_attribute a on a.attrelid=rc.oid and a.attnum=k.id)
      )), '[]'::jsonb) from pg_constraint fk join pg_class rc on rc.oid=fk.confrelid join pg_namespace rn on rn.oid=rc.relnamespace
      where fk.conrelid=c.oid and fk.contype='f' and rn.nspname='public')) order by c.relname)
    from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r'),
  'functions', (select jsonb_agg(jsonb_build_object('name',p.proname,'returns',format_type(p.prorettype,null), 'set',p.proretset,
    'args',(select coalesce(jsonb_agg(jsonb_build_object('name',p.proargnames[k.n], 'type',format_type(k.id,null),
      'optional',k.n>p.pronargs-p.pronargdefaults) order by k.n),'[]'::jsonb)
      from unnest(p.proargtypes::oid[]) with ordinality k(id,n))) order by p.proname)
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'
      and p.prorettype<>'trigger'::regtype and has_function_privilege('authenticated',p.oid,'EXECUTE')
      and not exists(select 1 from pg_depend dep where dep.objid=p.oid and dep.classid='pg_proc'::regclass and dep.deptype='e'))
);`
const raw = execFileSync(
  psql,
  [
    '-X',
    '-qAt',
    '-h',
    '127.0.0.1',
    '-p',
    '55439',
    '-U',
    'postgres',
    '-d',
    'postgres',
    '-v',
    'ON_ERROR_STOP=1',
    '-c',
    sql,
  ],
  { encoding: 'utf8', windowsHide: true }
)
const schema = JSON.parse(raw.trim())
const tables = new Set(schema.tables.map((table) => table.name))
function typeOf(type) {
  if (type.endsWith('[]')) return `(${typeOf(type.slice(0, -2))})[]`
  if (tables.has(type)) return `Database['public']['Tables']['${type}']['Row']`
  if (/^(?:smallint|integer|bigint|numeric|real|double precision)/.test(type)) return 'number'
  if (type === 'boolean') return 'boolean'
  if (type === 'jsonb' || type === 'json') return 'Json'
  if (type === 'void') return 'undefined'
  if (/^(?:uuid|text|character|timestamp|date|time|inet)/.test(type)) return 'string'
  throw new Error(`Unmapped PostgreSQL type: ${type}`)
}
const lines = [
  '// Generated by scripts/generate-database-types.mjs from repository migrations on local PostgreSQL.',
  '// This describes the repository schema, not a claim of inspecting hosted Supabase.',
  'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]',
  'export type Database = { public: { Tables: {',
]
for (const table of schema.tables) {
  lines.push(`  ${table.name}: {`)
  for (const mode of ['Row', 'Insert', 'Update']) {
    lines.push(`    ${mode}: {`)
    for (const column of table.columns) {
      const optional =
        mode === 'Update' ||
        (mode === 'Insert' && (column.nullable || column.defaulted || column.generated))
      const type =
        column.generated && mode !== 'Row'
          ? 'never'
          : typeOf(column.type) + (column.nullable ? ' | null' : '')
      lines.push(`      ${column.name}${optional ? '?' : ''}: ${type}`)
    }
    lines.push('    }')
  }
  lines.push(`    Relationships: ${JSON.stringify(table.relations)}`, '  }')
}
lines.push('}; Views: { [_ in never]: never }; Functions: {')
for (const fn of schema.functions || []) {
  lines.push(`  ${fn.name}: { Args: ${fn.args.length ? '{' : 'Record<PropertyKey, never>'}`)
  for (const arg of fn.args)
    lines.push(`    ${arg.name}${arg.optional ? '?' : ''}: ${typeOf(arg.type)} | null`)
  lines.push(
    `  ${fn.args.length ? '}' : ''}; Returns: ${typeOf(fn.returns)}${fn.set ? '[]' : ''} }`
  )
}
lines.push(
  '}; Enums: { [_ in never]: never }; CompositeTypes: { [_ in never]: never } } }',
  "export type TableName = keyof Database['public']['Tables']",
  "export type Tables<Name extends TableName> = Database['public']['Tables'][Name]['Row']",
  "export type TablesInsert<Name extends TableName> = Database['public']['Tables'][Name]['Insert']",
  "export type TablesUpdate<Name extends TableName> = Database['public']['Tables'][Name]['Update']",
  ''
)
await mkdir(new URL('../src/types', import.meta.url), { recursive: true })
await writeFile(new URL('../src/types/database.types.ts', import.meta.url), lines.join('\n'))
console.log(
  `Generated ${schema.tables.length} tables and ${schema.functions.length} RPC definitions from local PostgreSQL.`
)
